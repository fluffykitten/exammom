values
  ('mom-assets', 'mom-assets', true),
  ('mom-docs', 'mom-docs', true),
  ('mom-pdfs', 'mom-pdfs', true)
on conflict (id) do nothing;

-- Storage Policies
drop policy if exists "Public read mom buckets" on storage.objects;
create policy "Public read mom buckets" on storage.objects
  for select using (bucket_id in ('mom-assets', 'mom-docs', 'mom-pdfs'));

drop policy if exists "Public upload docs and pdfs" on storage.objects;
create policy "Public upload docs and pdfs" on storage.objects
  for insert with check (bucket_id in ('mom-docs', 'mom-pdfs'));

drop policy if exists "Admin manage mom assets and delete" on storage.objects;
create policy "Admin manage mom assets and delete" on storage.objects
  for all to authenticated
  using (bucket_id in ('mom-assets', 'mom-docs', 'mom-pdfs'))
  with check (bucket_id in ('mom-assets', 'mom-docs', 'mom-pdfs'));

