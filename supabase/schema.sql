-- Semester Exam Minutes of Meeting (MoM) Generator — Supabase Schema & Seed
-- Run this entire script in your Supabase Project -> SQL Editor.

create extension if not exists pgcrypto;

-- 1. App Settings (PDF Header & Left/Right Logos)
create table if not exists public.app_settings (
  id text primary key default 'default',
  header_institution text not null default 'INSAN CENDEKIA MADANI',
  header_title text not null default 'MINUTES OF MEETING',
  header_subtitle text not null default '2nd Semester Exam',
  header_address text not null default 'Official Examination Invigilation Report',
  left_logo_url text,
  right_logo_url text,
  footer_note text not null default 'Generated by Semester Exam MoM System',
  updated_at timestamptz not null default now()
);

-- 2. Configurable Form Fields
create table if not exists public.form_fields (
  id uuid primary key default gen_random_uuid(),
  field_key text unique not null,
  label text not null,
  description text,
  field_type text not null,
  required boolean not null default true,
  options jsonb not null default '[]'::jsonb,
  section text not null default 'general',
  sort_order integer not null default 0,
  is_active boolean not null default true,
  is_system boolean not null default false
);

-- 3. Exam Rooms
create table if not exists public.rooms (
  id uuid primary key default gen_random_uuid(),
  name text unique not null,
  category text not null default 'AKHWAT',
  sort_order integer not null default 0,
  is_active boolean not null default true
);

-- 4. Room Students Roster
create table if not exists public.students (
  id uuid primary key default gen_random_uuid(),
  room_id uuid not null references public.rooms(id) on delete cascade,
  student_no integer not null,
  nis text not null,
  name text not null,
  kelas text not null,
  is_active boolean not null default true
);
create unique index if not exists students_room_nis_idx on public.students(room_id, nis);

-- 5. Submitted Minutes of Meeting PDFs
create table if not exists public.submissions (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  invigilator_name text not null,
  invigilator_email text not null,
  exam_day text,
  exam_date date,
  room_id uuid references public.rooms(id) on delete set null,
  room_name text not null,
  session text,
  subjects text[] not null default '{}',
  attendees_count integer not null default 0,
  expected_count integer not null default 0,
  absent_count integer not null default 0,
  absent_students jsonb not null default '[]'::jsonb,
  form_snapshot jsonb not null,
  documentation_url text,
  pdf_url text not null,
  pdf_path text not null
);

-- Enable Row Level Security
alter table public.app_settings enable row level security;
alter table public.form_fields enable row level security;
alter table public.rooms enable row level security;
alter table public.students enable row level security;
alter table public.submissions enable row level security;

-- Public Read Policies (anyone can load the form & view shared PDFs)
drop policy if exists "Public read app_settings" on public.app_settings;
create policy "Public read app_settings" on public.app_settings for select using (true);

drop policy if exists "Public read form_fields" on public.form_fields;
create policy "Public read form_fields" on public.form_fields for select using (true);

drop policy if exists "Public read rooms" on public.rooms;
create policy "Public read rooms" on public.rooms for select using (true);

drop policy if exists "Public read students" on public.students;
create policy "Public read students" on public.students for select using (true);

drop policy if exists "Public read submissions" on public.submissions;
create policy "Public read submissions" on public.submissions for select using (true);

-- Public Submit Policy (invigilators can submit without logging in)
drop policy if exists "Public insert submissions" on public.submissions;
create policy "Public insert submissions" on public.submissions for insert with check (true);

-- Admin Write Policies (authenticated Supabase Auth users)
drop policy if exists "Admin write app_settings" on public.app_settings;
create policy "Admin write app_settings" on public.app_settings for all to authenticated using (true) with check (true);

drop policy if exists "Admin write form_fields" on public.form_fields;
create policy "Admin write form_fields" on public.form_fields for all to authenticated using (true) with check (true);

drop policy if exists "Admin write rooms" on public.rooms;
create policy "Admin write rooms" on public.rooms for all to authenticated using (true) with check (true);

drop policy if exists "Admin write students" on public.students;
create policy "Admin write students" on public.students for all to authenticated using (true) with check (true);

drop policy if exists "Admin delete submissions" on public.submissions;
create policy "Admin delete submissions" on public.submissions for delete to authenticated using (true);

-- Storage Buckets
